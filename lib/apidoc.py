"""Generate API.md: every public helper an episode can use, with its signature and the first line of its docstring.

  python3 lib/apidoc.py        # rewrites API.md at the kit root

Sessions read API.md instead of the library source, which keeps each reel's context (and usage) small.
Re-run after changing a helper's signature or docstring, and commit API.md with it.
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = [('episode', 'E', 'Driver runtime: import episode as E'),
           ('gt', 'K', 'Easing, captions, cards, expressions: import gt as K'),
           ('iso', '', 'Isometric camera and primitives: from iso import ...'),
           ('world', 'Wd', 'Fonts, text, labels, colours, atmosphere: import world as Wd'),
           ('chars', '', 'Krishna and Arjun busts (normally used through E.bust / E.standing_bust)')]


def sig(fn):
    a = fn.args
    parts = []
    pos = a.posonlyargs + a.args
    defaults = [None]*(len(pos) - len(a.defaults)) + list(a.defaults)
    for arg, d in zip(pos, defaults):
        parts.append(arg.arg + ('' if d is None else '=' + ast.unparse(d)))
    if a.vararg:
        parts.append('*' + a.vararg.arg)
    for arg, d in zip(a.kwonlyargs, a.kw_defaults):
        parts.append(arg.arg + ('' if d is None else '=' + ast.unparse(d)))
    if a.kwarg:
        parts.append('**' + a.kwarg.arg)
    return f"{fn.name}({', '.join(parts)})"


out = ['# API', '',
       'Generated by `lib/apidoc.py` from the library source. Read this instead of the source; open a file in `lib/` only',
       'when something breaks or a helper here is unclear.', '']
for mod, alias, title in MODULES:
    tree = ast.parse((ROOT / 'lib' / f'{mod}.py').read_text())
    out += [f'## {mod}.py  ({title})', '']
    consts = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            n = node.targets[0].id
            if n.isupper() and not n.startswith('_'):
                consts.append(n)
    if consts:
        out += ['Constants: ' + ', '.join(f'`{c}`' for c in consts), '']
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and not node.name.startswith('_'):
            doc = (ast.get_docstring(node) or '').strip().split('\n\n')[0].replace('\n', ' ')
            head = f'class {node.name}' if isinstance(node, ast.ClassDef) else sig(node)
            prefix = f'{alias}.' if alias else ''
            out.append(f'- `{prefix}{head}`' + (f': {doc}' if doc else ''))
            if isinstance(node, ast.ClassDef):
                for m in node.body:
                    if isinstance(m, ast.FunctionDef) and (not m.name.startswith('_') or m.name == '__init__'):
                        mdoc = (ast.get_docstring(m) or '').strip().split('\n')[0]
                        out.append(f'  - `{sig(m)}`' + (f': {mdoc}' if mdoc else ''))
    out.append('')
(ROOT / 'API.md').write_text('\n'.join(out))
print('wrote', ROOT / 'API.md', len('\n'.join(out)), 'chars')
